#!/usr/bin/env python3
"""
Склеивает рельеф (`app/src/main/assets/track_relief.json`, шаг 15) в ОДНУ сквозную шкалу
высот на весь документ — а не как сейчас, где `height_pt` честен только в пределах одной
страницы (`source`+`page`), потому что PyMuPDF вытаскивает координаты кривой как есть из
PDF, а каждая страница профиля нарисована со своим независимо подобранным вертикальным
масштабом/сдвигом (см. докстринг `extract_relief.py`).

Машинист заметил, откуда можно взять калибровку не гадая: соседние страницы одного PDF
физически ПЕРЕСЕКАЮТСЯ — последний км+пк одной страницы совпадает с (несколькими) первыми
км+пк следующей (проверено: у большинства пар соседних страниц `Хилок-Крм.pdf` — 10 общих
пикетов, т.е. ровно 1 км внахлёст). Раз это ТА ЖЕ физическая точка path, у неё должна
получаться ОДНА высота — значит по общим пикетам можно найти сдвиг для новой страницы, чтобы
её сырые высоты легли на уже откалиброванную шкалу предыдущей, и раскатать калибровку цепочкой
through весь документ (страница 0 — эталон, offset=0).

Изначально пробовал ещё и подгонять МАСШТАБ (не только сдвиг) линейной регрессией по общим
пикетам — но проверил на реальных данных и отказался: окно нахлёста — это всего ~10 пикетов
на границе (около 1 км), и высота рельефа на таком коротком отрезке обычно меняется всего на
единицы-первые-десятки pt, поэтому наклон (масштаб) в МНК определяется почти целиком шумом
округления, а не настоящей разницей масштабов страниц (проверено: у пары страниц 21→22
`Хилок-Крм.pdf` МНК давал масштаб 0.23, хотя сырые высоты этих же страниц на границе
совпадают почти один в один — то есть верный масштаб там ~1.0). Поэтому здесь только СДВИГ
(scale всегда 1) — это менее точно, если реальная разница масштабов между страницами и
правда есть, но не сеет искусственные скачки/растяжения из шумной подгонки, чего и просил
машинист.

Если у пары страниц общих пикетов НЕТ (несколько пар в начале `Хилок-Крм.pdf`, а также обе
страницы `Крм-Чернышевск.pdf`/`Чернышевск-Крм.pdf` целиком — там страницы стыкуются встык, без
нахлёста), берём последнюю точку предыдущей страницы и первую точку новой как "одна и та же
примерно точка" (это физически соседние пикеты, 100 м друг от друга — не то же место, но
ближайшее доступное) и подгоняем сдвиг по ней.

Каждая из 4 связок (source+direction) — Хилок-Крм.pdf/чётное, Крм-Хилок.pdf/нечётное,
Крм-Чернышевск.pdf/чётное, Чернышевск-Крм.pdf/нечётное — склеивается ОТДЕЛЬНО (независимая
цепочка страниц одного документа). Между парами чёт/неч, кроющими один и тот же физический
перегон в двух документах, калибровка НЕ сверяется — это была бы другая, более сложная
задача (у них в принципе может быть разное перо/масштаб независимо от того, что это те же
километры), машинист просил именно про соседние страницы одного документа.

Результат — новое поле `height_stitched` рядом с исходным `height_pt` (тот не трогаем, он
остаётся как есть, честный "как в PDF"). `height_stitched` — то, что использовать в графике:
одна сквозная шкала (произвольные единицы — те же pt, что и раньше, калибровки в метры по-
прежнему нет, см. шаг 15), но БЕЗ разрывов на границах страниц.
"""
import sys
import json
from collections import defaultdict


def chainage(e):
    return e['km'] * 1000 + (e['pk'] - 1) * 100


def stitch_group(entries):
    by_page = defaultdict(list)
    for e in entries:
        by_page[e['page']].append(e)
    pages = sorted(by_page)
    for p in pages:
        by_page[p].sort(key=chainage)

    offset = {pages[0]: 0.0}
    log = []
    for i in range(1, len(pages)):
        prev_p, cur_p = pages[i - 1], pages[i]
        prev_offset = offset[prev_p]
        prev_by_kmpk = {(e['km'], e['pk']): e['height_pt'] for e in by_page[prev_p]}
        cur_by_kmpk = {(e['km'], e['pk']): e['height_pt'] for e in by_page[cur_p]}
        shared = sorted(set(prev_by_kmpk) & set(cur_by_kmpk))

        if shared:
            diffs = [(prev_by_kmpk[k] + prev_offset) - cur_by_kmpk[k] for k in shared]
            b = sum(diffs) / len(diffs)
            method = f'{len(shared)} общих пикетов'
        else:
            # Номер страницы не всегда растёт вместе с км — у "обратных" документов
            # (например, Крм-Хилок.pdf/нечётное) страницы идут в порядке проезда, а км
            # при этом убывает, так что физическая граница может лежать у НАЧАЛА
            # предыдущей страницы и КОНЦА следующей, а не наоборот. Поэтому не гадаем,
            # а берём из обеих крайних точек каждой страницы ту пару, что реально ближе
            # друг к другу по км+пк.
            prev_edges = (by_page[prev_p][0], by_page[prev_p][-1])
            cur_edges = (by_page[cur_p][0], by_page[cur_p][-1])
            last_prev, first_cur = min(
                ((p, c) for p in prev_edges for c in cur_edges),
                key=lambda pc: abs(chainage(pc[0]) - chainage(pc[1])),
            )
            b = (last_prev['height_pt'] + prev_offset) - first_cur['height_pt']
            method = 'нет общих пикетов — по ближайшим краевым точкам'

        offset[cur_p] = b
        log.append((prev_p, cur_p, b, method))

    for p in pages:
        b = offset[p]
        for e in by_page[p]:
            e['height_stitched'] = round(e['height_pt'] + b, 2)

    return log


def main():
    in_path = sys.argv[1] if len(sys.argv) > 1 else 'app/src/main/assets/track_relief.json'
    out_path = sys.argv[2] if len(sys.argv) > 2 else in_path

    with open(in_path, encoding='utf-8') as f:
        data = json.load(f)

    groups = defaultdict(list)
    for e in data:
        groups[(e['source'], e['direction'])].append(e)

    for key, entries in groups.items():
        log = stitch_group(entries)
        print(f'{key[0]} ({key[1]}): {len(log)} стыков')
        for prev_p, cur_p, b, method in log:
            print(f'  стр.{prev_p} -> стр.{cur_p}: offset={b:+.1f}  ({method})')

    with open(out_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, separators=(',', ':'))
    print(f'\nWrote {out_path}')


if __name__ == '__main__':
    main()
