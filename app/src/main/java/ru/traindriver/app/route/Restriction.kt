package ru.traindriver.app.route

/**
 * Одно временное ограничение скорости, введённое машинистом (ТЗ раздел 11, "Ограничения" —
 * сам машинист называет их "предупреждения"). Не то же самое, что постоянные [SpeedLimit] из
 * speed_limits.json — это ручной ввод, без источника в данных, живёт только в памяти приложения
 * на время смены (ТЗ ничего не говорит о сохранении между запусками, в HTML-макете тоже нет
 * персистентности — осознанное допущение).
 *
 * [endM] >= [startM]; точечное ограничение (только начало) — [endM] == [startM]. [path] — null
 * означает "правильный путь текущего направления" (ТЗ: "пусто = правильный путь текущего
 * направления"), число — конкретный путь по обычному правилу чётный/нечётный.
 */
data class Restriction(
    val startM: Double,
    val endM: Double,
    val speedKmh: Int,
    val path: Int?
)

/**
 * Список ограничений отсортирован (ТЗ раздел 11): по возрастанию для чётного направления,
 * по убыванию для нечётного — тот же порядок, в котором растут/убывают пикеты этого направления.
 */
fun List<Restriction>.sortedForDirection(direction: Direction): List<Restriction> =
    if (direction == Direction.EVEN) sortedBy { it.startM } else sortedByDescending { it.startM }
