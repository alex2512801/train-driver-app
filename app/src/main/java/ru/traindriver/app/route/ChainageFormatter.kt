package ru.traindriver.app.route

import kotlin.math.floor

/**
 * Перевод пикетажа (расстояния от начала маршрута в метрах) в формат "км+пк".
 *
 * ТЗ раздел 7: "Координата (км+пк, по тапу переключается в формат КЛУБ-У)" — то есть это
 * ДВА РАЗНЫХ формата, а не один:
 *   - [format] — обычный км+пк, показывается по умолчанию. Именно в этом формате записаны
 *     все остальные данные (speed_limits.json, сигналы, пробы тормозов — например
 *     "Хилок (5932 пк 7 - 5935 пк 3)"): км = floor(метры/1000), пк = floor(метры%1000/100)+1.
 *   - [formatKlubU] — отдельный, отличающийся на +1 к км формат КЛУБ-У, включается по тапу
 *     на координату. км = floor(метры/1000)+1. Именно эта формула (с примерами
 *     0000.050 -> 1км 1пк; 6234.670 -> 6235км 7пк) была в ТЗ — но она про КЛУБ-У, а не про
 *     обычный км+пк, которым размечены остальные данные. Раньше в коде эта формула ошибочно
 *     использовалась как единственная и универсальная — из-за этого весь график скорости был
 *     сдвинут на 1 км относительно реальной позиции.
 *
 * [toMeters] — обратное к [format] (обычному км+пк, не КЛУБ-У), потому что именно в этом
 * формате записаны исходные км+пк во всех остальных наборах данных.
 */
object ChainageFormatter {

    /** Обычный км+пк — формат по умолчанию (ТЗ раздел 7). */
    fun format(totalMeters: Double): String {
        val (km, pk) = kmPk(totalMeters)
        return "${km}км ${pk}пк"
    }

    /** Формат КЛУБ-У — отдельный, включается по тапу на координату (ТЗ раздел 7). */
    fun formatKlubU(totalMeters: Double): String {
        val (km, pk) = kmPk(totalMeters)
        return "${km + 1}км ${pk}пк"
    }

    private fun kmPk(totalMeters: Double): Pair<Int, Int> {
        val clamped = totalMeters.coerceAtLeast(0.0)
        val kmIndex = floor(clamped / 1000.0)
        val metersInKm = clamped - kmIndex * 1000.0
        val pk = floor(metersInKm / 100.0).toInt() + 1
        return kmIndex.toInt() to pk
    }

    /** Обратное преобразование: начало пикета [pk] километра [km] (обычный км+пк) в метрах. */
    fun toMeters(km: Int, pk: Int): Double = km * 1000.0 + (pk - 1) * 100.0
}
